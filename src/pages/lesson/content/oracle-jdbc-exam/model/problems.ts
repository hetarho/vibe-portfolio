import type { TableKey, UnitKey } from './units'

export type Level = '하급' | '중급' | '상급'

/**
 * 기출 시험지에 나온 문제 모양.
 * 서술은 "~을 서술하시오", 용어는 설명을 읽고 이름 쓰기, 빈칸은 문장 빈칸과 '가능·불가능' 채우기,
 * 고르기는 "모두 고르시오", 코드 빈칸은 [코드]의 ______ 채우기, 코드 작성은 SQL·자바를 끝까지 쓰기,
 * 실행 결과는 [코드]를 보고 결과 쓰기, 오류는 에러가 나는 이유를 쓰고 고치기다.
 */
export type AskType = '서술' | '용어' | '빈칸' | '고르기' | '코드 빈칸' | '코드 작성' | '실행 결과' | '오류'

/** 시험지에서 문제 문장 아래에 대괄호 이름을 달고 붙는 덩어리. 기출의 [보기]·[코드]·[실행 결과]·[문제]를 따른다 */
export type ExamBlock = {
  label: '보기' | '문제' | '코드' | '실행 결과' | '테이블'
  lines: string[]
}

/**
 * 문자열 안의 `코드`와 **강조**는 ui/RichText가 화면용 글꼴로 바꿔 그린다.
 * 화면에서만 쓰는 정보(제목·표본·테이블·함정)는 시험지 모양과 따로 붙였다.
 */
export type ExamProblem = {
  /** 문제집 번호. 화면 코드 Q{no}와 같다 */
  no: number
  unit: UnitKey
  /** 머리말 [Oracle - 단원]의 단원 칸 (기초, DQL, 함수, JOIN …) */
  topic: string
  level: Level
  points: 6 | 11 | 16
  askType: AskType
  /** 전체 목록(O 키)과 헤드라인에 쓰는 짧은 제목 */
  title: string
  /** 시험지의 문제 문장. 끝의 배점 (6점)은 화면과 문제집이 붙인다 */
  question: string
  /** 문제 문장 아래에 붙는 [보기]·[코드]·[실행 결과] 등. 시험지에 나오는 순서대로 둔다 */
  blocks?: ExamBlock[]
  /** 결과 예측용 표본 EXAM_EMP를 문제 옆에 띄운다 */
  sample?: boolean
  /** 열 이름을 봐야 풀 수 있는 문제에 띄우는 테이블 */
  tables?: TableKey[]
  /** 정답. 코드보다 먼저 보인다 */
  answer: string[]
  answerCode?: string[]
  /** 코드 뒤에 붙는 해설 */
  explain?: string[]
  /** 자주 틀리는 지점 */
  trap?: string
}

/** 고정폭으로 줄을 맞춰 보여 줄 덩어리. [보기]와 [문제]는 문장으로 읽힌다 */
export function isMonoBlock(block: ExamBlock) {
  return block.label === '코드' || block.label === '실행 결과' || block.label === '테이블'
}

/** 기출의 머리말 "[Java - 기초] 하급문제"와 같은 모양 */
export function examHeading(problem: ExamProblem) {
  return `[Oracle - ${problem.topic}] ${problem.level}문제`
}

